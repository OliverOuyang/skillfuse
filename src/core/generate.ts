function buildDatasetSchema(a: SkillAnalysis, datasetName: string) {
  return {
    name: datasetName,
    description: `Evaluation dataset for the "${a.skillName}" skill. Generated by SkillFuse on ${DAY}.`,
    metadata: {
      skill: a.skillName,
      generator: "skillfuse",
      generator_version: "0.1.0",
      task_types: inferTaskTypes(a),
      formats: a.formats,
    },
    item_schema: {
      input: {
        task: "string — the user request that should trigger the skill",
        context: "object — optional attachments / constraints for the run",
      },
      expectedOutput: {
        must_include: "string[] — elements a passing output must contain",
        must_not_include: "string[] — elements a passing output must not contain",
        format: "string — expected output format",
        reference_outline: "string[] — expected section structure (when applicable)",
        notes: "string — grading notes for this item",
      },
      metadata: {
        source: "skill-body | skill-example | constraint-adversarial | llm-augmented",
        section: "string — originating section of the skill",
        tags: "string[]",
        difficulty: "basic | intermediate | edge",
      },
    },
    usage: [
      "python: langfuse.create_dataset(name=..., description=..., metadata=...)",
      "then langfuse.create_dataset_item(dataset_name=..., input=..., expected_output=..., metadata=...)",
    ],
  };
}

function buildDatasetItems(a: SkillAnalysis): DatasetItem[] {
  const items: DatasetItem[] = [];
  const skillRef = a.description ? a.description.slice(0, 160) : a.displayName;

  // 1. happy-path items from trigger keywords / steps
  const triggers = a.triggerKeywords.length > 0 ? a.triggerKeywords : [a.displayName];
  for (const t of triggers.slice(0, 3)) {
    items.push({
      input: {
        task: synthesizeTask(t, a),
        context: {},
      },
      expectedOutput: {
        must_include: mustInclude(a),
        must_not_include: mustNotInclude(a),
        format: a.formats[0] || "markdown",
        reference_outline: a.outputSections.length > 0 ? a.outputSections : a.steps.slice(0, 5),
        notes: `Happy-path item derived from trigger "${t}". Fill in a concrete reference answer before relying on exact-match scoring.`,
      },
      metadata: {
        source: "skill-body",
        section: "description",
        tags: ["happy-path", a.skillName],
        difficulty: "basic",
      },
    });
  }

  // 2. example-based items from code blocks in the skill
  for (const ex of a.examples.slice(0, 3)) {
    items.push({
      input: {
        task: `Produce the output demonstrated in the skill example${ex.caption ? ` (${ex.caption})` : ""} for the skill "${a.skillName}".`,
        context: { example_language: ex.lang },
      },
      expectedOutput: {
        must_include: ex.code
          .split("\n")
          .map((l) => l.trim())
          .filter((l) => l.length > 10)
          .slice(0, 5),
        format: ex.lang || a.formats[0] || "text",
        reference: ex.code.slice(0, 2000),
        notes: "Reference taken verbatim from a code block inside the skill body.",
      },
      metadata: {
        source: "skill-example",
        section: ex.caption,
        tags: ["example", a.skillName],
        difficulty: "intermediate",
      },
    });
  }

  // 3. constraint-adversarial items
  for (const c of a.constraints.slice(0, 2)) {
    items.push({
      input: {
        task: `${synthesizeTask(triggers[0], a)} (This run specifically probes the constraint: "${c}")`,
        context: { probe_constraint: c },
      },
      expectedOutput: {
        must_not_include: mustNotInclude(a),
        format: a.formats[0] || "markdown",
        notes: `Adversarial item: a passing answer must respect the hard rule "${c}".`,
      },
      metadata: {
        source: "constraint-adversarial",
        section: "constraints",
        tags: ["constraint", "edge-case", a.skillName],
        difficulty: "edge",
      },
    });
  }

  if (items.length === 0) {
    items.push({
      input: { task: `Use the "${a.skillName}" skill: ${skillRef}`, context: {} },
      expectedOutput: {
        must_include: mustInclude(a),
        format: a.formats[0] || "markdown",
        notes: "Fallback item — no triggers, examples or constraints were detected in the skill.",
      },
      metadata: { source: "skill-body", section: "", tags: [a.skillName], difficulty: "basic" },
    });
  }

  return items.slice(0, 8);
}

function synthesizeTask(trigger: string, a: SkillAnalysis): string {
  const inputHint = a.inputs.length > 0 ? `, given ${a.inputs[0]}` : "";
  return `A user asks${inputHint}: "${trigger}". Execute the "${a.skillName}" skill end-to-end and produce its expected deliverable.`;
}

function mustInclude(a: SkillAnalysis): string[] {
  const out: string[] = [];
  if (a.outputFields.length > 0) out.push(...a.outputFields.slice(0, 4));
  else if (a.outputSections.length > 0) out.push(...a.outputSections.slice(0, 4));
  else if (a.steps.length > 0) out.push(...a.steps.slice(0, 3).map((s) => s.slice(0, 60)));
  if (a.formats.includes("table")) out.push("a rendered table");
  if (a.formats.includes("code")) out.push("a code block");
  return out;
}

function mustNotInclude(a: SkillAnalysis): string[] {
  const out: string[] = [];
  for (const c of a.constraints) {
    const quoted = [...c.matchAll(/["'“”`]([^"'“”`]{2,60})["'“”`]/g)].map((m) => m[1]);
    if (/never|禁止|不得|不要|avoid|forbidden/i.test(c)) out.push(...quoted.slice(0, 2));
  }
  return [...new Set(out)].slice(0, 6);
}

function inferTaskTypes(a: SkillAnalysis): string[] {
  const t: string[] = [];
  if (a.formats.some((f) => ["pptx", "docx", "xlsx", "pdf", "html", "image"].includes(f))) t.push("artifact-generation");
  if (a.formats.includes("code")) t.push("code-generation");
  if (a.formats.some((f) => ["report", "markdown", "chart"].includes(f))) t.push("writing-and-analysis");
  if (a.tools.length > 3) t.push("tool-use");
  return t.length > 0 ? t : ["general"];
}

