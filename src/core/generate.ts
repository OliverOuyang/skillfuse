export function buildRuleChecks(a: SkillAnalysis): RuleCheck[] {
  const rules: RuleCheck[] = [
    {
      id: "non_empty",
      name: "Output is non-empty",
      description: "The model produced a substantive answer.",
      kind: "non_empty",
      params: {},
      weight: 1,
      source: "universal",
    },
    {
      id: "min_length",
      name: "Minimum length",
      description: "The answer is long enough to plausibly complete the skill.",
      kind: "min_length",
      params: { min: a.formats.some((f) => ["report", "pptx", "docx"].includes(f)) ? 400 : 120 },
      weight: 1,
      source: "format heuristic",
    },
  ];

  if (a.formats.includes("json")) {
    rules.push({
      id: "valid_json",
      name: "Valid JSON",
      description: "Output parses as JSON (the skill declares JSON output).",
      kind: "valid_json",
      params: {},
      weight: 2,
      source: "declared format: json",
    });
  }
  if (a.formats.includes("markdown") || a.formats.includes("report")) {
    rules.push({
      id: "has_heading",
      name: "Has heading structure",
      description: "Markdown output contains at least one heading.",
      kind: "has_heading",
      params: {},
      weight: 1,
      source: "declared format: markdown/report",
    });
  }
  if (a.formats.includes("table")) {
    rules.push({
      id: "has_table",
      name: "Contains a table",
      description: "Output contains a markdown table.",
      kind: "has_table",
      params: {},
      weight: 1,
      source: "declared format: table",
    });
  }
  if (a.formats.includes("code")) {
    rules.push({
      id: "has_code_block",
      name: "Contains a code block",
      description: "Output contains at least one fenced code block.",
      kind: "has_code_block",
      params: {},
      weight: 2,
      source: "declared format: code",
    });
  }

  // banned terms from never-constraints
  const banned = mustNotInclude(a);
  if (banned.length > 0) {
    rules.push({
      id: "no_banned_terms",
      name: "Respects hard constraints",
      description: `Output must not contain: ${banned.join(", ")}.`,
      kind: "not_contains",
      params: { terms: banned },
      weight: 3,
      source: "skill constraints (never/禁止)",
    });
  }

  // emoji ban is common in skills
  if (a.constraints.some((c) => /emoji/i.test(c) && /never|禁止|不得|不要|avoid|no /i.test(c))) {
    rules.push({
      id: "no_emoji",
      name: "No emoji",
      description: "The skill forbids emoji in the deliverable.",
      kind: "no_emoji",
      params: {},
      weight: 2,
      source: "skill constraint: no emoji",
    });
  }

  // required sections — prefer concrete output fields over section headings
  const required = (a.outputFields.length > 0 ? a.outputFields : a.outputSections).slice(0, 5);
  if (required.length > 0) {
    rules.push({
      id: "required_sections",
      name: "Required sections present",
      description: `Output should cover: ${required.join(" / ")}.`,
      kind: "contains_any",
      params: { terms: required, min_match: Math.max(1, Math.ceil(required.length / 2)) },
      weight: 2,
      source: "skill output-structure section",
    });
  }

  return rules;
}

