function emitPackReadme(a: SkillAnalysis, rules: RuleCheck[], items: DatasetItem[]): string {
  return `# ${a.skillName}-eval — Langfuse evaluation pack

Generated by **SkillFuse** on ${DAY} from the skill's \`SKILL.md\`.

## What's inside

| File | Purpose |
| --- | --- |
| \`dataset_schema.json\` | Langfuse-compatible dataset definition (schema + metadata) |
| \`dataset_items.json\` | ${items.length} dataset items (happy-path, example-based, constraint-adversarial) |
| \`rule_scorers.py\` | ${rules.length} deterministic scorers, zero-dependency, weighted aggregate |
| \`rule_checks.json\` | the same rules as data — drives the SkillFuse in-browser test runner |
| \`llm_judge_prompt.md\` | LLM-as-a-judge rubric derived from the skill's quality criteria |
| \`llm_judge.py\` | judge scorer wired to any OpenAI-compatible endpoint |
| \`langfuse_config.py\` | one-shot dataset creation + evaluation-run skeleton |
| \`.env.example\` | environment template |

## Quick start

\`\`\`bash
pip install langfuse openai python-dotenv
cp .env.example .env   # fill in Langfuse keys (and judge model if used)
python langfuse_config.py
\`\`\`

## Notes

- Items marked \`"source": "skill-body"\` contain template \`expectedOutput\`s — replace them with
  concrete reference answers before relying on exact-match grading.
- Rule scorers are deterministic and free; the LLM judge is optional and only runs when
  \`JUDGE_API_KEY\` is set.
`;
}
